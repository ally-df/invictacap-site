/** Unknown glyph fallback: a hollow box. */
const MISSING = ["#####", "#...#", "#...#", "#...#", "#...#", "#...#", "#####"];

export function glyph(ch: string): string[] {
  const up = ch.toUpperCase();
  return G[up] ?? MISSING;
}

export type Cell = { x: number; y: number };

/** Width in cells of a single line of text. */
export function measureLine(text: string): number {
  let w = 0;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (ch === " ") {
      w += SPACE_W + LETTER_SPACING;
      continue;
    }
    w += GLYPH_W + LETTER_SPACING;
  }
  return Math.max(0, w - LETTER_SPACING);
}

/**
 * Lay out lines of text into filled cells. y grows downward, x rightward.
 * `align` controls how shorter lines sit inside the widest line.
 * Returns cells plus total width/height in cells.
 */
export function layoutText(
  lines: readonly string[],
  align: "left" | "center" | "right" = "left",
): { cells: Cell[]; width: number; height: number } {
  const widths = lines.map(measureLine);
  const width = Math.max(0, ...widths);
  const height = lines.length * GLYPH_H + Math.max(0, lines.length - 1) * LINE_SPACING;
  const cells: Cell[] = [];

  lines.forEach((line, li) => {
    const lineW = widths[li];
    const offsetX = align === "center" ? Math.floor((width - lineW) / 2) : align === "right" ? width - lineW : 0;
    const baseY = li * (GLYPH_H + LINE_SPACING);
    let cx = offsetX;
    for (let i = 0; i < line.length; i++) {
      const ch = line[i];
      if (ch === " ") {
        cx += SPACE_W + LETTER_SPACING;
        continue;
      }
      const rows = glyph(ch);
      for (let r = 0; r < GLYPH_H; r++) {
        const row = rows[r];
        for (let c = 0; c < GLYPH_W; c++) {
          if (row[c] === "#") cells.push({ x: cx + c, y: baseY + r });
        }
      }
      cx += GLYPH_W + LETTER_SPACING;
    }
  });

  return { cells, width, height };
}
